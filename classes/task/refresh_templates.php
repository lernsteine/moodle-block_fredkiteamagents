namespace block_fredkiteamagents\task;

use block_fredkiteamagents\local\templates;

/**
 * Every hour: ask the licence server which agent templates exist in FredKI.
 *
 * Done here and not while a course page is drawn, so nobody waits for the licence server.
 *
 * @package    block_fredkiteamagents
 * @copyright  2026 lernsteine.com
 * @license    https://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class refresh_templates extends \core\task\scheduled_task {
    /**
     * Name of the task.
     *
     * @return string
     */
    public function get_name(): string {
        return get_string('task_refreshtemplates', 'block_fredkiteamagents');
    }

    /**
     * Ask the licence server.
     */
    public function execute(): void {
        templates::refresh(true);
    }
}
